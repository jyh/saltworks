@dataclass
class Commit:
    when: datetime
    sha: str
    subject: str
    insertions: int = 0
    ext_insertions: int = 0  # insertions in files matching the tracked extension


def git_commits(
    repo: str | Path,
    since: str,
    until: str | None = None,
    ext: str = ".lean",
) -> list[Commit]:
    """Commits in [since, until), newest last, with insertion counts.

    ``since``/``until`` MUST carry an explicit time. ``--since='2026-07-23'``
    without one is parsed as UTC and silently drops commits (measured in the
    leg-1 harvest: 654 vs 712 over the same nominal window).
    """
    repo = str(Path(repo).resolve())
    args = [
        "git",
        "-C",
        repo,
        "log",
        f"--since={since}",
        "--numstat",
        "--date=format-local:%Y-%m-%dT%H:%M:%S%z",
        "--format=@@%H|%ad|%s",
        "--no-merges",
    ]
    if until:
        args.insert(6, f"--until={until}")
    env = dict(os.environ, TZ="America/Los_Angeles")
    out = subprocess.run(args, capture_output=True, text=True, env=env, check=True).stdout

    commits: list[Commit] = []
    cur: Commit | None = None
    for line in out.splitlines():
        if line.startswith("@@"):
            sha, ad, subject = line[2:].split("|", 2)
            cur = Commit(when=datetime.fromisoformat(ad).astimezone(TZ), sha=sha, subject=subject)
            commits.append(cur)
            continue
        if not line.strip() or cur is None:
            continue
        parts = line.split("\t")
        if len(parts) != 3:
            continue
        added, _removed, path = parts
        if added == "-":
            continue  # binary
        n = int(added)
        cur.insertions += n
        if path.endswith(ext):
            cur.ext_insertions += n
    commits.sort(key=lambda c: c.when)
    return commits


# a ceremonial seat prefix: "play M: ", "saltworks: ", "evidence: "
PREFIX_RE = re.compile(r"^[A-Za-z][\w .+-]{0,20}:\s+")
TAG_RE = re.compile(r"^([A-Za-z0-9][A-Za-z0-9'.’-]*)")
STOPWORDS = {"THE", "A", "AN", "OUR", "ITS"}


def wave_label(subject: str) -> str:
    """A coarse wave tag from a commit subject.

    Waves in this fleet are named in the subject line -- ``N4B-W2c(...)``,
    ``WEIL-TRIO W4-e ...``, ``THE PEARL --- ...`` -- usually behind a
    ceremonial seat prefix (``play M: ``, ``saltworks: ``). This strips up
    to two such prefixes and takes the leading token, keeping a second
    word when the first is an article. It is deliberately dumb: a grouping
    aid for the token table, not a measured quantity.
    """
    s = subject.strip()
    for _ in range(2):
        m = PREFIX_RE.match(s)
        if not m:
            break
        s = s[m.end():]
    m = TAG_RE.match(s)
    if not m:
        return "(unlabelled)"
    tag = m.group(1)
    if tag.upper() in STOPWORDS:
        rest = s[len(tag):].lstrip()
        m2 = TAG_RE.match(rest)
        if m2:
            tag = f"{tag} {m2.group(1)}"
    if len(tag) < 2:
        return "(unlabelled)"
    return tag


def fmt_int(n: int | float) -> str:
    return f"{int(n):,}"


def fmt_hours(seconds: float) -> str:
    h = int(seconds // 3600)
    m = int((seconds % 3600) // 60)
    return f"{h}h {m:02d}m"


def fmt_dur_h(seconds: float) -> str:
    return f"{seconds / 3600:.1f} h"


def rejection_table(stats: ParseStats) -> str:
    """The Amendment-2 disclosure block, rendered as markdown."""
    lines = [
        "| Record class | Verdict | Count |",
        "|---|---|---:|",
    ]
    for label, n in sorted(stats.accepted.items(), key=lambda kv: -kv[1]):
        lines.append(f"| `{label}` | **counted as human** | {fmt_int(n)} |")
    for label, n in sorted(stats.rejected.items(), key=lambda kv: -kv[1]):
        lines.append(f"| `{label}` | rejected | {fmt_int(n)} |")
    return "\n".join(lines)


